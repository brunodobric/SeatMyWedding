import Foundation

/// Bilo koja JSON vrijednost. Podaci vjenčanja čuvaju se kao JSON (isto kao na
/// webu i u Firestoreu), pa polja koja Swift ne poznaje ne smiju nestati.
public enum JSONValue: Equatable, Sendable {
    case null
    case bool(Bool)
    case number(Double)
    case string(String)
    case array([JSONValue])
    case object([String: JSONValue])
}

extension JSONValue: Codable {
    public init(from decoder: Decoder) throws {
        let c = try decoder.singleValueContainer()
        if c.decodeNil() {
            self = .null
        } else if let n = try? c.decode(Double.self) {
            self = .number(n)
        } else if let b = try? c.decode(Bool.self) {
            self = .bool(b)
        } else if let s = try? c.decode(String.self) {
            self = .string(s)
        } else if let a = try? c.decode([JSONValue].self) {
            self = .array(a)
        } else if let o = try? c.decode([String: JSONValue].self) {
            self = .object(o)
        } else {
            throw DecodingError.dataCorruptedError(in: c, debugDescription: "Nepodržana JSON vrijednost")
        }
    }

    public func encode(to encoder: Encoder) throws {
        var c = encoder.singleValueContainer()
        switch self {
        case .null: try c.encodeNil()
        case .bool(let b): try c.encode(b)
        case .number(let n): try c.encode(n)
        case .string(let s): try c.encode(s)
        case .array(let a): try c.encode(a)
        case .object(let o): try c.encode(o)
        }
    }
}

extension JSONValue {
    public var objectValue: [String: JSONValue]? {
        if case .object(let o) = self { return o }
        return nil
    }

    public var arrayValue: [JSONValue]? {
        if case .array(let a) = self { return a }
        return nil
    }

    public var stringValue: String? {
        if case .string(let s) = self { return s }
        return nil
    }

    public var numberValue: Double? {
        if case .number(let n) = self { return n }
        return nil
    }

    /// Kao JavaScriptova "truthy" vrijednost (null, false, 0 i "" su neistina).
    public var isTruthy: Bool {
        switch self {
        case .null: return false
        case .bool(let b): return b
        case .number(let n): return n != 0 && !n.isNaN
        case .string(let s): return !s.isEmpty
        case .array, .object: return true
        }
    }

    /// Zamjenjuje brojeve koje JSON ne može prikazati (NaN, beskonačno) s null.
    /// Firestore ih ne prihvaća, a web ih izbacuje na isti način.
    public func sanitized() -> JSONValue {
        switch self {
        case .number(let n): return n.isFinite ? self : .null
        case .array(let a): return .array(a.map { $0.sanitized() })
        case .object(let o): return .object(o.mapValues { $0.sanitized() })
        default: return self
        }
    }
}
